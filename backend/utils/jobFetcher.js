// Asynchronously fetches fresh live remote developer jobs from public API
export const fetchLiveRemoteJobs = async () => {
    try {
        const response = await fetch("https://remotive.com/api/remote-jobs?category=software-dev&limit=15", {
            headers: { "Accept": "application/json" }
        });
        if (!response.ok) return [];

        const data = await response.json();
        const liveJobs = (data.jobs || []).map((j, idx) => ({
            _id: `remotive_${j.id || idx}`,
            title: j.title,
            companyName: j.company_name,
            companyLogo: j.company_logo || "https://images.unsplash.com/photo-1618005182384-a83a8bd57fbe?w=128&auto=format&fit=crop&q=80",
            location: j.candidate_required_location || "Remote Worldwide",
            salary: j.salary ? parseFloat(j.salary.replace(/[^0-9.]/g, '')) || 25 : 24 + (idx % 15),
            experienceLevel: 2,
            jobType: j.job_type === "full_time" ? "Full Time" : "Contract",
            position: 2,
            requirements: j.tags && j.tags.length > 0 ? j.tags.slice(0, 5) : ["Software Engineering", "Full Stack", "APIs"],
            description: j.description ? j.description.replace(/<[^>]*>?/gm, '').slice(0, 450) + "..." : "Exciting remote engineering role.",
            applyUrl: j.url,
            isExternal: true,
            source: "Remotive Live Feed",
            applications: [],
            createdAt: new Date(j.publication_date || Date.now())
        }));

        return liveJobs;
    } catch (error) {
        console.warn("Live API fetch timed out or offline, using curated tier-1 tech jobs:", error.message);
        return [];
    }
};
